export function getContinentLabel(value: string): string {
  const continent = CONTINENTS_COUNTRIES.find((c) => c.value === value);
  return continent?.label ?? value;
}

export function getCountryLabel(
  continentValue: string,
  countryValue: string,
): string {
  const continent = CONTINENTS_COUNTRIES.find(
    (c) => c.value === continentValue,
  );
  const country = continent?.countries.find((co) => co.value === countryValue);
  return country?.label ?? countryValue;
}

export function formatContinentCountry(value: unknown): string {
  if (typeof value !== "object" || value === null) return String(value ?? "");
  const obj = value as Record<string, string>;
  const continent = obj.continent ? getContinentLabel(obj.continent) : "";
  const country = obj.country
    ? getCountryLabel(obj.continent ?? "", obj.country)
    : "";
  if (continent && country) return `${continent} - ${country}`;
  return continent || country || "";
}
